import pandas as pd
import gspread
from gspread_dataframe import get_as_dataframe
import os

# --- Configuration ---
SERVICE_ACCOUNT_FILE = os.path.join('secrets', 'finsup2-proj-90ea4909d4c5.json')
SPREADSHEET_URL = 'https://docs.google.com/spreadsheets/d/1-4fo3txGNMK8OyIzdYqGilrcmGb81VHDtT0BVLD5BMY/edit?gid=867136461#gid=867136461'
WORKSHEET_NAME = "Lista ETF-ów"
# The local CSV file for remapping
REMAPPING_FILE_PATH = os.path.join(os.getcwd(), 'app', 'tests', 'ETF.csv')
OUTPUT_FILE_PATH = os.path.join(os.getcwd(), 'app', 'tickers_lists', 'etf_list.py')

# --- Main Script ---
print("--- Starting Ticker Processing and Remapping Script ---")

# 1. Authenticate and Load Data from Google Sheets
print("Step 1: Authenticating with Google Sheets and loading data...")
if not os.path.exists(SERVICE_ACCOUNT_FILE):
    print(f"Error: Service account key not found at '{SERVICE_ACCOUNT_FILE}'.")
    exit()
try:
    gc = gspread.service_account(filename=SERVICE_ACCOUNT_FILE)
    spreadsheet = gc.open_by_url(SPREADSHEET_URL)
    worksheet = spreadsheet.worksheet(WORKSHEET_NAME)
    # Load without headers to use integer-based indexing
    gsheet_df = get_as_dataframe(worksheet, evaluate_formulas=True, header=None).copy()
    print("Data loaded successfully from Google Sheets.")
except Exception as e:
    print(f"An error occurred during Google Sheet access: {e}")
    exit()

# 2. Filter DataFrame based on criteria
print("\nStep 2: Filtering data based on specified criteria...")
try:
    gsheet_df.iloc[:, 13] = gsheet_df.iloc[:, 13].astype(str) # Column N
    gsheet_df.iloc[:, 14] = gsheet_df.iloc[:, 14].astype(str) # Column O
    gsheet_df.iloc[:, 16] = pd.to_numeric(gsheet_df.iloc[:, 16], errors='coerce') # Column Q
    gsheet_df.iloc[:, 5] = gsheet_df.iloc[:, 5].astype(str) # Column F

    # Define filtering conditions
    condition1 = (gsheet_df.iloc[:, 13].str.lower() == 'tak') # Column N ('N')
    condition2 = (gsheet_df.iloc[:, 14].str.lower() == 'tak') # Column O ('O')
    condition3 = (gsheet_df.iloc[:, 16] > 1000)              # Column Q (Volume)
    condition4 = (gsheet_df.iloc[:, 5] != 'Akcje - technologia') # Exclude if Column F is 'Akcje - technologia'

    print("Applying the following filtering conditions:")
    print("- Column 'N' must be 'tak' OR Column 'O' must be 'tak'")
    print("- Column 'Q' (numeric value) must be greater than 1000")
    print("- Column 'F' must not be 'Akcje - technologia'")

    filtered_df = gsheet_df[(condition1 | condition2) & condition3 & condition4].copy()
    print(f"Found {len(filtered_df)} tickers after filtering.")
except Exception as e:
    print(f"An error occurred during data filtering: {e}")
    exit()

# 3. Load Remapping File and Create Lookup Dictionary
print(f"\nStep 3: Loading remapping data from '{REMAPPING_FILE_PATH}'...")
if not os.path.exists(REMAPPING_FILE_PATH):
    print(f"Error: Remapping file not found at '{REMAPPING_FILE_PATH}'.")
    exit()
try:
    # Read the CSV with semicolon delimiter and handle potential empty values
    remap_df = pd.read_csv(REMAPPING_FILE_PATH, delimiter=';')
    # Create a dictionary for mapping: Key='Ticker', Value='Yfinance mapped'
    # Drop rows where 'Ticker' or 'Yfinance mapped' is NaN to avoid errors
    remap_df.dropna(subset=['Ticker', 'Yfinance mapped'], inplace=True)
    ticker_map = pd.Series(remap_df['Yfinance mapped'].values, index=remap_df['Ticker']).to_dict()
    print("Successfully created ticker remapping dictionary.")
except Exception as e:
    print(f"An error occurred while reading or processing the remapping CSV: {e}")
    exit()

# 4. Remap Tickers and Write to File
print("\nStep 4: Remapping filtered tickers and writing to file...")
original_tickers = filtered_df.iloc[:, 1].tolist() # Tickers are in Column B
remapped_tickers = []
not_found_tickers = []

for ticker in original_tickers:
    if ticker in ticker_map:
        remapped_tickers.append(ticker_map[ticker])
    else:
        not_found_tickers.append(ticker)

print(f"Successfully remapped {len(remapped_tickers)} tickers.")
if not_found_tickers:
    print(f"Warning: {len(not_found_tickers)} tickers were not found in the remapping file and will be skipped:")
    print(not_found_tickers)

final_list_entries = [f'    "{ticker}",\n' for ticker in remapped_tickers]

print(f"\nWriting {len(final_list_entries)} remapped entries to {OUTPUT_FILE_PATH}...")

try:
    with open(OUTPUT_FILE_PATH, 'w', encoding='utf-8') as f:
        f.write('# -*- coding: utf-8 -*-\n')
        f.write('# This file is auto-generated by validate_etf.py using a local remapping file.\n\n')
        f.write('etf_list = [\n')
        f.writelines(final_list_entries)
        f.write(']\n')
    print("File written successfully.")
except IOError as e:
    print(f"Error: Could not write to file '{OUTPUT_FILE_PATH}': {e}")
    exit()

print(f"\n--- Script finished successfully. Saved {len(remapped_tickers)} remapped tickers. ---")
